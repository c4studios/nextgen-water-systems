/** every suburb once, A to Z */
export const ALL_SUBURBS: string[] = Array.from(new Set(AREAS.flatMap((a) => a.suburbs))).sort((a, b) => a.localeCompare(b));

/** the region a suburb sits in, matched loosely (case and spacing) */
export function areaFor(suburb: string): { suburb: string; area: Area } | null {
  const key = suburb.trim().toLowerCase().replace(/\s+/g, " ");
  if (!key) return null;
  for (const area of AREAS) {
    const hit = area.suburbs.find((s) => s.toLowerCase() === key);
    if (hit) return { suburb: hit, area };
  }
  return null;
}
