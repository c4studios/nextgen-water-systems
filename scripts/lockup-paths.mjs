// Bakes the Next Gen cover lockup into glyph outlines in centimetres, so the
// lettering can be extruded as real relief on the cover (Machine.tsx). Run
// after changing the lockup numbers in dims.ts:  node scripts/lockup-paths.mjs
import fs from "node:fs";
import opentype from "opentype.js";

const buf = fs.readFileSync(new URL("./fonts/michroma.ttf", import.meta.url));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const upm = font.unitsPerEm;
const capH = font.tables.os2.sCapHeight || font.charToGlyph("H").getBoundingBox().y2;

// the lockup, from dims.ts (COVER.lockup): line, its cap height in cm, the
// width it is fitted to, and how: "scale" fits by size, "track" by tracking
const WIDTH = 34;
const LINES = [
  { id: "name", text: "NEXT GEN", cap: 3.4, cy: 60.5, mode: "scale" },
  { id: "sub", text: "WATER SYSTEMS", cap: 1.75, cy: 55.9, mode: "track" },
  { id: "tag", text: "NEXT GENERATION WATER PROTECTION", cap: 0.95, cy: 51.6, mode: "track" },
];

const fmt = (n) => (Math.round(n * 1000) / 1000).toString();
const out = [];
for (const L of LINES) {
  const size = (L.cap / capH) * upm; // font size in cm per em
  // charToGlyph per character: the font's GSUB tables trip opentype.js 2.0's shaper
  const glyphs = [...L.text].map((ch) => font.charToGlyph(ch));
  const adv = glyphs.map((g) => (g.advanceWidth / upm) * size);
  let natural = adv.reduce((a, b) => a + b, 0);
  // kerning is left out on purpose: the cover lettering is tracked wide
  let scale = 1;
  let track = 0;
  if (L.mode === "scale" || natural > WIDTH) scale = WIDTH / natural;
  else track = (WIDTH - natural) / (glyphs.length - 1);
  const s = size * scale;
  const paths = [];
  let x = -WIDTH / 2;
  const yBase = L.cy - (L.cap * scale) / 2; // centre the cap height on cy
  glyphs.forEach((g, i) => {
    const p = g.getPath(x, 0, s); // y down, baseline at 0
    let d = "";
    for (const c of p.commands) {
      if (c.type === "M") d += `M${fmt(c.x)} ${fmt(yBase - c.y)}`;
      else if (c.type === "L") d += `L${fmt(c.x)} ${fmt(yBase - c.y)}`;
      else if (c.type === "C") d += `C${fmt(c.x1)} ${fmt(yBase - c.y1)} ${fmt(c.x2)} ${fmt(yBase - c.y2)} ${fmt(c.x)} ${fmt(yBase - c.y)}`;
      else if (c.type === "Q") d += `Q${fmt(c.x1)} ${fmt(yBase - c.y1)} ${fmt(c.x)} ${fmt(yBase - c.y)}`;
      else if (c.type === "Z") d += "Z";
    }
    if (d) paths.push(d);
    x += adv[i] * scale + track;
  });
  out.push({ id: L.id, cap: L.cap * scale, paths });
  console.log(L.id, "natural", natural.toFixed(2), "scale", scale.toFixed(3), "track", track.toFixed(3), "glyph paths", paths.length);
}
const ts = `/**
 * THE LOCKUP AS OUTLINES. Generated by scripts/lockup-paths.mjs from
 * Michroma (OFL) at the sizes in dims.ts; centimetres, y up, x centred on the
 * cover. Do not edit by hand; re-run the script.
 */
export type LockupLine = { id: string; cap: number; paths: string[] };
export const LOCKUP: LockupLine[] = ${JSON.stringify(out)};
`;
fs.writeFileSync(new URL("../src/components/machine/lockupPaths.ts", import.meta.url), ts);
console.log("written src/components/machine/lockupPaths.ts", ts.length, "chars");
